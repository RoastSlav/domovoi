//! `cargo xtask docs-config`: regenerate `docs/book/src/reference/configuration.md` from the
//! JSON schemas of `hub.toml` and `agent.toml` (printed by the hidden `domovoi schema`
//! subcommand), or check that it is up to date.

use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

use serde_json::{Map, Value};

/// Where the generated page is committed.
pub const PAGE_PATH: &str = "docs/book/src/reference/configuration.md";

/// Writes the page, or with `check` fails when the committed page is stale.
pub fn run(root: &Path, check: bool) -> anyhow::Result<()> {
    let hub = schema(root, "hub")?;
    let agent = schema(root, "agent")?;
    let page = render(&hub, &agent);
    let path = root.join(PAGE_PATH);
    if check {
        let committed = std::fs::read_to_string(&path).unwrap_or_default();
        if committed.replace("\r\n", "\n") != page {
            anyhow::bail!("{PAGE_PATH} is stale: run `cargo xtask docs-config`");
        }
        println!("docs-config: {PAGE_PATH} is up to date");
    } else {
        std::fs::write(&path, page)?;
        println!("docs-config: wrote {PAGE_PATH}");
    }
    Ok(())
}

fn schema(root: &Path, file: &str) -> anyhow::Result<Value> {
    println!("==> docs-config: cargo run -q -p domovoi -- schema {file}");
    let output = Command::new("cargo")
        .current_dir(root)
        .args([
            "run", "-q", "--locked", "-p", "domovoi", "--", "schema", file,
        ])
        .output()?;
    if !output.status.success() {
        anyhow::bail!(
            "`domovoi schema {file}` failed:\n{}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    Ok(serde_json::from_slice(&output.stdout)?)
}

const INTRO: &str = "# Configuration reference

<!-- Generated by `cargo xtask docs-config` from the configuration schemas. Do not edit by hand. -->

You do not need a configuration file: the hub is set up in its web UI, and an agent writes its own `agent.toml` when it enrolls. This page lists every setting for when you want to [manage configuration as code](../install/config-as-code.md), or to change an agent's checks.

Each table lists a section's keys. A key's description gives its default; a key without one is required when its section is present. Any scalar can also be set with an environment variable, `DOMOVOI_<SECTION>__<KEY>`, as described in [config as code](../install/config-as-code.md#environment-variables).

Value types:

- **duration**: a string such as `\"30s\"`, `\"5m\"`, `\"24h\"`, `\"7d\"` or `\"1h30m\"`.
- **time**: a local time of day, `\"HH:MM\"`.
- **time zone**: an IANA name such as `\"Europe/Sofia\"`.
- **secret**: never written inline: `{ env = \"VARIABLE\" }` reads an environment variable, `{ file = \"/path\" }` reads a file only its owner can read.

To check a file, run `domovoi check config <file>`.
";

/// The whole page.
pub fn render(hub: &Value, agent: &Value) -> String {
    let mut out = String::from(INTRO);
    for (file, schema) in [("hub.toml", hub), ("agent.toml", agent)] {
        let _ = write!(out, "\n## `{file}`\n\n{}\n", one_line(description(schema)));
        let defs = schema
            .get("$defs")
            .and_then(Value::as_object)
            .cloned()
            .unwrap_or_default();
        let r = Renderer { defs: &defs };
        if let Some(props) = schema.get("properties").and_then(Value::as_object) {
            for (key, field) in props {
                r.section(&mut out, key, field, 3);
            }
        }
    }
    out
}

struct Renderer<'a> {
    defs: &'a Map<String, Value>,
}

/// What a field holds, once `$ref` and `Option` are looked through.
enum Shape<'a> {
    /// A table with its own keys.
    Table(&'a Value),
    /// A list of tables.
    ListOfTables(&'a Value),
    /// A map from names to tables.
    MapOfTables(&'a Value),
    /// Anything shown as one row.
    Value,
}

impl Renderer<'_> {
    fn resolve<'v>(&'v self, schema: &'v Value) -> &'v Value {
        if let Some(name) = schema
            .get("$ref")
            .and_then(Value::as_str)
            .and_then(|r| r.strip_prefix("#/$defs/"))
            && let Some(def) = self.defs.get(name)
        {
            return def;
        }
        if let Some(inner) = non_null(schema) {
            return self.resolve(inner);
        }
        schema
    }

    fn shape<'v>(&'v self, schema: &'v Value) -> Shape<'v> {
        let resolved = self.resolve(schema);
        if resolved.get("properties").is_some() {
            return Shape::Table(resolved);
        }
        if let Some(items) = resolved.get("items") {
            let item = self.resolve(items);
            if item.get("properties").is_some() {
                return Shape::ListOfTables(item);
            }
        }
        if let Some(values) = resolved
            .get("additionalProperties")
            .filter(|v| v.is_object())
        {
            let value = self.resolve(values);
            if value.get("properties").is_some() {
                return Shape::MapOfTables(value);
            }
        }
        Shape::Value
    }

    /// A heading and table for `key`, then its nested tables.
    fn section(&self, out: &mut String, key: &str, field: &Value, depth: usize) {
        let hashes = "#".repeat(depth.min(6));
        let (header, table) = match self.shape(field) {
            Shape::Table(table) => (format!("[{key}]"), table),
            Shape::ListOfTables(table) => (format!("[[{key}]]"), table),
            Shape::MapOfTables(table) => (format!("[{key}.<name>]"), table),
            Shape::Value => {
                let _ = write!(
                    out,
                    "\n{hashes} `{key}`\n\n{}\n\n| Type |\n| --- |\n| {} |\n",
                    one_line(description(field)),
                    cell(&self.type_name(field))
                );
                return;
            }
        };
        let _ = write!(
            out,
            "\n{hashes} `{header}`\n\n{}\n",
            one_line(description(field))
        );
        let Some(props) = table.get("properties").and_then(Value::as_object) else {
            return;
        };
        let mut nested = Vec::new();
        let mut rows = String::new();
        for (name, prop) in props {
            if matches!(self.shape(prop), Shape::Value) {
                let _ = writeln!(
                    rows,
                    "| `{name}` | {} | {} |",
                    cell(&self.type_name(prop)),
                    cell(&one_line(description(prop)))
                );
            } else {
                nested.push((name, prop));
            }
        }
        if !rows.is_empty() {
            let _ = write!(
                out,
                "\n| Key | Type | Meaning |\n| --- | --- | --- |\n{rows}"
            );
        }
        let prefix = header
            .trim_start_matches('[')
            .trim_end_matches(']')
            .trim_start_matches('[');
        for (name, prop) in nested {
            self.section(out, &format!("{prefix}.{name}"), prop, depth + 1);
        }
    }

    fn type_name(&self, schema: &Value) -> String {
        if let Some(inner) = non_null(schema) {
            return self.type_name(inner);
        }
        if let Some(name) = schema
            .get("$ref")
            .and_then(Value::as_str)
            .and_then(|r| r.strip_prefix("#/$defs/"))
        {
            return match name {
                "Duration" => "duration".to_owned(),
                "LocalTime" => "time".to_owned(),
                "TimeZone" => "time zone".to_owned(),
                "Secret" => "secret".to_owned(),
                _ => self
                    .defs
                    .get(name)
                    .map_or_else(|| name.to_owned(), |d| self.type_name(d)),
            };
        }
        if let Some(values) = schema.get("enum").and_then(Value::as_array) {
            return choices(values.iter());
        }
        if let Some(options) = schema.get("oneOf").and_then(Value::as_array) {
            let consts: Vec<&Value> = options.iter().filter_map(|o| o.get("const")).collect();
            if consts.len() == options.len() {
                return choices(consts.into_iter());
            }
        }
        if let Some(items) = schema.get("items") {
            return format!("list of {}", self.type_name(items));
        }
        if let Some(values) = schema.get("additionalProperties").filter(|v| v.is_object()) {
            return format!("map of {}", self.type_name(values));
        }
        let kind = match schema.get("type") {
            Some(Value::String(kind)) => kind.as_str(),
            Some(Value::Array(kinds)) => kinds
                .iter()
                .filter_map(Value::as_str)
                .find(|k| *k != "null")
                .unwrap_or("value"),
            _ => "value",
        };
        match (kind, schema.get("format").and_then(Value::as_str)) {
            ("string", Some("uri")) => "URL".to_owned(),
            ("string", Some("ip")) => "IP address".to_owned(),
            ("number", _) => "number".to_owned(),
            (kind, _) => kind.to_owned(),
        }
    }
}

/// The non-null alternative of an `Option`: `anyOf: [X, null]`.
fn non_null(schema: &Value) -> Option<&Value> {
    let options = schema.get("anyOf").and_then(Value::as_array)?;
    let mut rest = options
        .iter()
        .filter(|o| o.get("type").and_then(Value::as_str) != Some("null"));
    let only = rest.next()?;
    rest.next().is_none().then_some(only)
}

fn choices<'a>(values: impl Iterator<Item = &'a Value>) -> String {
    values
        .map(|v| match v {
            Value::String(s) => format!("`\"{s}\"`"),
            other => format!("`{other}`"),
        })
        .collect::<Vec<_>>()
        .join(" or ")
}

fn description(schema: &Value) -> &str {
    schema
        .get("description")
        .and_then(Value::as_str)
        .unwrap_or("")
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::render;

    #[test]
    fn sections_rows_and_nested_tables_render() {
        let hub = json!({
            "description": "The hub.",
            "properties": {
                "notify": {"description": "When.", "$ref": "#/$defs/Notify"},
                "probes": {"description": "Probes.", "type": "array", "items": {"$ref": "#/$defs/Probe"}}
            },
            "$defs": {
                "Notify": {"properties": {
                    "quiet": {"description": "Quiet | hours.", "type": "boolean"},
                    "digest": {"description": "The digest.", "anyOf": [{"$ref": "#/$defs/Digest"}, {"type": "null"}]}
                }},
                "Digest": {"properties": {"time": {"description": "When.", "$ref": "#/$defs/LocalTime"}}},
                "LocalTime": {"type": "string"},
                "Probe": {"properties": {"kind": {"oneOf": [{"const": "tcp"}, {"const": "http"}]}}}
            }
        });
        let agent = json!({"description": "The agent.", "properties": {}});
        let page = render(&hub, &agent);
        assert!(page.contains("### `[notify]`"), "{page}");
        assert!(
            page.contains("| `quiet` | boolean | Quiet \\| hours. |"),
            "{page}"
        );
        assert!(page.contains("#### `[notify.digest]`"), "{page}");
        assert!(page.contains("| `time` | time | When. |"), "{page}");
        assert!(page.contains("### `[[probes]]`"), "{page}");
        assert!(page.contains("`\"tcp\"` or `\"http\"`"), "{page}");
    }
}
