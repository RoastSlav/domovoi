//! The note text a profile turns into: what the machine looks like, what changed since the
//! last profile, then the tool output it was made from.
//!
//! The summary is short on purpose: a human reads it first, and a note search shows only
//! one line of the note, so the words that matter are at the top. Everything before
//! [`DETAILS_MARK`] is what triage and the chat overview are sent; the raw sections follow
//! so nothing the tools said is hidden.

use domovoi_core::Host;

use super::HostProfile;
use super::ProfileSection;
use super::collect::KERNEL_TITLE;
use super::cut;

/// The mark in the note where the raw tool output starts: everything before it is the
/// part a person scans and the part the model is sent, so triage and chat cut there.
const DETAILS_MARK: &str = "\n## Details";

/// The summary at the top of the note is cut to this many bytes.
const SUMMARY_LIMIT: usize = 2 * 1024;

/// The whole note stays under this many bytes.
const NOTE_LIMIT: usize = 64 * 1024;

/// Bytes in one GiB: memory is printed in the unit a person reads it.
const GIB: u64 = 1024 * 1024 * 1024;

/// The line that tells a reader this note is the hub's, not theirs.
const GENERATED_LINE: &str = "_Generated by Domovoi. It is replaced when the profile refreshes; write your own notes separately._";

/// The most containers and sockets the summary names one by one.
const MAX_LISTED: usize = 30;

/// The most kernel messages the summary quotes.
const MAX_LOG_LINES: usize = 5;

/// One summary line naming a list, or saying there is none.
pub(crate) fn summary_names(noun: &str, items: &[String]) -> String {
    let taken = items
        .iter()
        .take(MAX_LISTED)
        .map(|item| item.to_owned())
        .collect::<Vec<String>>();
    if taken.is_empty() {
        return format!("no {}", noun);
    }
    format!("{}: {}", noun, taken.join(", "))
}

/// The first lines of the kernel messages section, empty when there is none.
pub(crate) fn kernel_lines(profile: &HostProfile) -> Vec<String> {
    let found = profile
        .sections
        .iter()
        .find(|section| section.ok && section.title == KERNEL_TITLE);
    match found {
        None => [].to_vec(),
        Some(section) => section
            .text
            .lines()
            .take(MAX_LOG_LINES)
            .map(|line| line.trim_end().to_owned())
            .collect(),
    }
}

/// The recent changes as the note shows them, empty when the machine has not changed.
pub(crate) fn changes_block(profile: &HostProfile) -> String {
    if profile.changes.is_empty() {
        return String::new();
    }
    let lines = profile
        .changes
        .iter()
        .map(|change| format!("- {}", change))
        .collect::<Vec<String>>();
    format!("## Recent changes\n\n{}", lines.join("\n"))
}

/// One block per section: a heading and what the tool said, fenced as text.
pub(crate) fn details_lines(profile: &HostProfile) -> Vec<String> {
    profile.sections.iter().map(details_block).collect()
}

/// A fence longer than the longest run of backticks in `text`, so tool output cannot
/// close it early and write its own headings into the note.
pub(crate) fn fence_for(text: &str) -> String {
    let mut longest = 0;
    let mut run = 0;
    for mark in text.chars() {
        if mark == '`' {
            run += 1;
            longest = longest.max(run);
        } else {
            run = 0;
        }
    }
    "`".repeat((longest + 1).max(3))
}

/// One section as a heading plus its text fenced as a block, or why it did not answer.
pub(crate) fn details_block(section: &ProfileSection) -> String {
    if section.ok {
        let fence = fence_for(section.text.as_str());
        format!(
            "### {}\n\n{fence}\n{}\n{fence}",
            section.title, section.text
        )
    } else {
        format!(
            "### {}\n\nThe tool did not answer: {}",
            section.title, section.text
        )
    }
}

/// The top of the note: the facts, containers and ports a human scans first.
pub(crate) fn summary_lines(profile: &HostProfile) -> Vec<String> {
    let facts = &profile.facts;
    let running = profile
        .containers
        .iter()
        .filter(|line| line.state == "running")
        .count();
    let names = profile
        .containers
        .iter()
        .take(MAX_LISTED)
        .map(|unit| format!("{} ({})", unit.name, unit.image))
        .collect::<Vec<String>>();
    let container_line = if profile.containers.is_empty() {
        "no containers".to_owned()
    } else {
        format!(
            "{} containers ({} running): {}",
            profile.containers.len(),
            running,
            names.join(", ")
        )
    };
    let memory = facts.mem_total_bytes / GIB;
    let mut lines = [
        format!("{} on {}, kernel {}", facts.os, facts.arch, facts.kernel),
        format!("{} logical CPUs, {} GiB memory", facts.cpu_count, memory),
        container_line,
        summary_names("listening sockets", &profile.listeners),
        summary_names("read skills", &profile.skills),
        summary_names("checks", &profile.checks),
    ]
    .to_vec();
    let logs = kernel_lines(profile);
    if !logs.is_empty() {
        lines.push("last kernel messages:".to_owned());
        for line in logs {
            lines.push(line);
        }
    }
    lines
}

/// The whole note: the summary, what changed since the last profile, then the tool output.
pub(crate) fn markdown(host: &Host, profile: &HostProfile) -> String {
    let summary = cut(summary_lines(profile).join("\n"), SUMMARY_LIMIT);
    let details = details_lines(profile).join("\n\n");
    let blocks = [
        format!("# Host profile: {}\n\n{}", host.name, GENERATED_LINE),
        format!("Agent version {}.", profile.agent_version),
        format!("## Summary\n\n{}", summary),
        changes_block(profile),
        format!("## Details\n\n{}", details),
    ]
    .iter()
    .filter(|block| !block.trim().is_empty())
    .map(|block| block.to_owned())
    .collect::<Vec<String>>()
    .join("\n\n");
    cut(blocks, NOTE_LIMIT)
}

/// The part of the note a person scans and the model is sent: the summary and the recent
/// changes, without the raw tool output. Triers and the chat overview cut here so they read
/// the same words the host page shows.
pub(crate) fn summary(host: &Host, profile: &HostProfile) -> String {
    let text = markdown(host, profile);
    match text.find(DETAILS_MARK) {
        Some(at) => text[..at].trim_end().to_string(),
        None => text,
    }
}
