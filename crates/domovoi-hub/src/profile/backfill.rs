//! Copies a host profile's machine description into the knowledge store as a `host_platform`
//! fact, and labels the generated note as superseded.
//!
//! Containers, ports and skills in a profile are inventory and stay there; only the machine
//! description is knowledge.

use std::sync::Arc;

use domovoi_core::knowledge::{EvidenceKind, EvidenceRef, FactSource, Predicate, SubjectRef};
use domovoi_core::ports::{FactFilter, Page};
use domovoi_core::{Actor, HostId, NoteId, SYSTEM_PROFILE};
use domovoi_engine::knowledge::{FactDraft, KnowledgeService};
use serde_json::json;

use super::{GENERATED_TAG, HostProfile, ProfileDeps, ProfileError, stored};

/// The tag that marks a generated note whose content now lives in facts.
pub const SUPERSEDED_TAG: &str = "superseded-by-facts";

/// The line added under the generated notice of a superseded note.
pub(crate) const SUPERSEDED_LINE: &str =
    "_Superseded by facts: the machine description is kept as a fact on this host._";

/// The prefix of the generated notice, which a labelled note keeps.
const GENERATED_PREFIX: &str = "_Generated by Domovoi.";

/// `body` with the superseded line under the generated notice; unchanged when it already
/// has it or has no notice to follow.
#[must_use]
pub(crate) fn label_superseded(body: &str) -> String {
    if body.contains(SUPERSEDED_LINE) {
        return body.to_owned();
    }
    let Some(at) = body.find(GENERATED_PREFIX) else {
        return format!("{SUPERSEDED_LINE}\n\n{body}");
    };
    let end = body[at..].find('\n').map_or(body.len(), |n| at + n);
    format!("{}\n\n{}{}", &body[..end], SUPERSEDED_LINE, &body[end..])
}

/// The platform fact a profile describes.
fn platform_draft(host: HostId, profile: &HostProfile, note: NoteId) -> FactDraft {
    let facts = &profile.facts;
    FactDraft {
        subject: SubjectRef::Host(host),
        predicate: Predicate::HostPlatform,
        value: json!({
            "hostname": facts.hostname,
            "os": facts.os,
            "kernel": facts.kernel,
            "arch": facts.arch,
            "cpu_count": facts.cpu_count,
            "mem_total_bytes": facts.mem_total_bytes,
        }),
        source: FactSource::Discovered,
        observed_at: Some(profile.collected_at),
        valid_until: None,
        evidence: Some(EvidenceRef::new(EvidenceKind::Note, note.as_uuid())),
    }
}

/// Records the platform fact of `profile`. A failure is logged and never returned: the
/// profile itself is already saved and the next refresh tries again.
pub(crate) async fn observe(
    knowledge: &Arc<KnowledgeService>,
    host: HostId,
    profile: &HostProfile,
) {
    let Some(note) = profile.note else {
        return;
    };
    let actor = Actor::System(SYSTEM_PROFILE.to_owned());
    if let Err(err) = knowledge
        .record(platform_draft(host, profile, note), &actor)
        .await
    {
        tracing::warn!(%err, %host, "could not record the host platform fact");
    }
}

/// Labels the generated note `id` as superseded, keeping its text, id and tags.
pub(crate) async fn label_note(deps: &ProfileDeps, id: NoteId) -> Result<(), ProfileError> {
    let Some(mut note) = deps.notes.get(id).await? else {
        return Ok(());
    };
    if note.tags.iter().any(|tag| tag == SUPERSEDED_TAG)
        && note.body_markdown.contains(SUPERSEDED_LINE)
    {
        return Ok(());
    }
    if !note.tags.iter().any(|tag| tag == GENERATED_TAG) {
        return Ok(());
    }
    if !note.tags.iter().any(|tag| tag == SUPERSEDED_TAG) {
        note.tags.push(SUPERSEDED_TAG.to_owned());
    }
    note.body_markdown = label_superseded(&note.body_markdown);
    deps.notes.upsert(&note).await?;
    Ok(())
}

/// Whether the host already has a live `host_platform` fact. A read that fails counts as
/// "yes": the back-fill must not guess, and a later profile refresh records the fact anyway.
async fn has_platform_fact(knowledge: &Arc<KnowledgeService>, host: HostId) -> bool {
    let filter = FactFilter {
        subject: Some(SubjectRef::Host(host)),
        predicate: Some(Predicate::HostPlatform),
        ..FactFilter::default()
    };
    knowledge
        .facts(&filter, &Page::first(1))
        .await
        .map_or(true, |page| !page.items.is_empty())
}

/// Writes a `host_platform` fact for every host with a stored profile and a note id, and
/// labels each note. Running it again changes nothing.
pub async fn backfill(deps: &ProfileDeps) {
    let Some(knowledge) = deps.knowledge.clone() else {
        return;
    };
    let hosts = match deps.hosts.list_hosts().await {
        Ok(hosts) => hosts,
        Err(err) => {
            tracing::warn!(%err, "could not list the hosts to back-fill facts for");
            return;
        }
    };
    for host in hosts {
        let profile = match stored(deps, host.id).await {
            Ok(Some(profile)) => profile,
            Ok(None) => continue,
            Err(err) => {
                tracing::warn!(%err, "could not read a stored host profile");
                continue;
            }
        };
        let Some(note) = profile.note else {
            continue;
        };
        if !has_platform_fact(&knowledge, host.id).await {
            observe(&knowledge, host.id, &profile).await;
        }
        if let Err(err) = label_note(deps, note).await {
            tracing::warn!(%err, "could not label the host profile note");
        }
    }
}
