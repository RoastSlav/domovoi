//! The profile text the hub stores for a host reaches the model as its summary. It is not a
//! note, so it is never among the host notes the model can search.

use domovoi_core::TriageOutcome;
use domovoi_core::ports::SettingsRepo;

use domovoi_testkit::build::T0;

use crate::harness::{Setup, host_id, report, seen, world};

/// Stores `body` as the profile text of the world's host.
async fn put(w: &crate::harness::World, body: String) {
    SettingsRepo::set(
        &*w.store,
        &domovoi_core::profile_text_key(host_id()),
        &serde_json::json!({ "markdown": body, "collected_at": T0 }),
    )
    .await
    .unwrap();
}

#[tokio::test]
async fn triage_sees_the_profile_summary_but_not_the_tool_output_behind_it() {
    let w = world(Setup::default()).await;
    w.primary.push_text(report());
    put(
        &w,
        [
            "# Host profile: nas",
            "",
            "_Generated by Domovoi. It is replaced when the profile refreshes._",
            "",
            "Agent version 0.6.0.",
            "",
            "## Summary",
            "",
            "Debian GNU/Linux 13 on x86_64, kernel 6.12.0",
            "4 logical CPUs, 32 GiB memory",
            "disk usage was normal near 60 percent when this was collected",
            "",
            "## Recent changes",
            "",
            "- 2026-11-01 05:12 UTC: container backup added",
            "",
            "## Details",
            "",
            "### Overview",
            "",
            "```",
            "uptime: 41 days and the raw output the note never sends",
            "```",
        ]
        .join("\n"),
    )
    .await;

    assert!(matches!(w.run().await, TriageOutcome::Report(_)));

    let requests = w.primary.requests();
    let first = requests.first().expect("the model was asked once");
    let shown = seen(first);
    assert!(
        shown.contains("Host profile (the normal state of this host)"),
        "the profile has its own part",
    );
    assert!(
        shown.contains("disk usage was normal near 60 percent"),
        "the summary words of the note reach the model",
    );
    assert!(
        shown.contains("container backup added"),
        "the recent changes reach the model too",
    );
    assert!(
        !shown.contains("the raw output the note never sends"),
        "the tool output behind the note stays out of the request",
    );
    let notes_part = shown
        .split("## Host notes")
        .last()
        .expect("the Host notes part")
        .split("## Skills you may propose")
        .next();
    assert!(
        !notes_part
            .expect("a part after the Host notes heading")
            .contains("Host profile: nas"),
        "the generated profile is not listed again where the model searches notes",
    );
}

/// A note an installation wrote before the hub changed its note keeps the older raw output
/// heading: that output must stay out of the request as well, until the note is refreshed.
#[tokio::test]
async fn a_profile_note_the_hub_wrote_earlier_cuts_its_tool_output_too() {
    let w = world(Setup::default()).await;
    w.primary.push_text(report());
    put(
        &w,
        [
            "# Host profile: nas",
            "",
            "Agent version 0.5.9.",
            "",
            "## What the machine looks like",
            "",
            "Debian GNU/Linux 12 on x86_64, 4 logical CPUs, 32 GiB memory",
            "",
            "## What the tools said",
            "",
            "### Overview",
            "",
            "```",
            "uptime: 41 days and the raw output an old note never sends",
            "```",
        ]
        .join("\n"),
    )
    .await;

    assert!(matches!(w.run().await, TriageOutcome::Report(_)));

    let requests = w.primary.requests();
    let first = requests.first().expect("the model was asked once");
    let shown = seen(first);
    assert!(
        shown.contains("Host profile (the normal state of this host)"),
        "the profile still has its own part",
    );
    assert!(
        shown.contains("4 logical CPUs, 32 GiB memory"),
        "the text before the older heading reaches the model",
    );
    assert!(
        !shown.contains("the raw output an old note never sends"),
        "the tool output behind the older heading stays out of the request",
    );
}
