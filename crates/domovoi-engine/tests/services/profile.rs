//! The profile note the hub generated for a host reaches the model as its summary, and
//! is not listed again among the host notes the model can search.

use domovoi_core::ports::NoteRepo;
use domovoi_core::{Note, NoteId, TriageOutcome};

use domovoi_testkit::build::T0;

use crate::harness::{Setup, host_id, report, seen, world};

/// The tag the hub puts on the note it generates from the host profile; the engine
/// copies it because it cannot see the hub.
const PROFILE_TAG: &str = "host-profile";

#[tokio::test]
async fn triage_sees_the_profile_summary_but_not_the_tool_output_behind_it() {
    let w = world(Setup::default()).await;
    w.primary.push_text(report());
    let note = Note {
        id: NoteId::new(),
        host: Some(host_id()),
        title: "Host profile: nas".to_owned(),
        body_markdown: [
            "# Host profile: nas",
            "",
            "_Generated by Domovoi. It is replaced when the profile refreshes._",
            "",
            "Agent version 0.6.0.",
            "",
            "## Summary",
            "",
            "Debian GNU/Linux 13 on x86_64, kernel 6.12.0",
            "4 logical CPUs, 32 GiB memory",
            "disk usage was normal near 60 percent when this was collected",
            "",
            "## Recent changes",
            "",
            "- 2026-11-01 05:12 UTC: container backup added",
            "",
            "## Details",
            "",
            "### Overview",
            "",
            "```",
            "uptime: 41 days and the raw output the note never sends",
            "```",
        ]
        .join("\n")
        .to_owned(),
        tags: [PROFILE_TAG, "generated"]
            .iter()
            .map(|tag| tag.to_string())
            .collect(),
        updated_at: T0,
    };
    NoteRepo::upsert(&*w.store, &note).await.unwrap();

    assert!(matches!(w.run().await, TriageOutcome::Report(_)));

    let requests = w.primary.requests();
    let first = requests.first().expect("the model was asked once");
    let shown = seen(first);
    assert!(
        shown.contains("Host profile (the normal state of this host)"),
        "the profile has its own part",
    );
    assert!(
        shown.contains("disk usage was normal near 60 percent"),
        "the summary words of the note reach the model",
    );
    assert!(
        shown.contains("container backup added"),
        "the recent changes reach the model too",
    );
    assert!(
        !shown.contains("the raw output the note never sends"),
        "the tool output behind the note stays out of the request",
    );
    let notes_part = shown
        .split("## Host notes")
        .last()
        .expect("the Host notes part")
        .split("## Skills you may propose")
        .next();
    assert!(
        !notes_part
            .expect("a part after the Host notes heading")
            .contains("Host profile: nas"),
        "the generated profile is not listed again where the model searches notes",
    );
}
